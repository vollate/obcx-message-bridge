#!/usr/bin/env python3
"""Generate the bridge's standalone-emoji property ranges from Unicode 17.0."""

import argparse
import hashlib
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("data", type=Path, help="Unicode 17.0 emoji-data.txt")
parser.add_argument("output", type=Path, help="Generated C++ header path")
args = parser.parse_args()
source = args.data.read_bytes()
text = source.decode("utf-8")
if "# Version: 17.0\n" not in text:
    parser.error("expected Unicode emoji-data.txt version 17.0")

properties = {"Emoji": set(), "Emoji_Component": set()}
for line in text.splitlines():
    record = line.partition("#")[0].strip()
    if not record:
        continue
    interval, name = (part.strip() for part in record.split(";"))
    if name not in properties:
        continue
    bounds = interval.split("..")
    first, last = int(bounds[0], 16), int(bounds[-1], 16)
    properties[name].update(range(first, last + 1))
if not all(properties.values()):
    parser.error("missing Emoji or Emoji_Component property")

ranges = []
for scalar in sorted(properties["Emoji"] - properties["Emoji_Component"]):
    if ranges and scalar == ranges[-1][1] + 1:
        ranges[-1][1] = scalar
    else:
        ranges.append([scalar, scalar])
entries = "\n".join(f"    {{0x{first:X}U, 0x{last:X}U}}," for first, last in ranges)
header = f"""#pragma once

// Generated by scripts/generate_reaction_emoji_ranges.py; do not hand-edit.
// Unicode 17.0 Emoji minus Emoji_Component (not a QQ acceptance whitelist).
// Source: https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt
// SHA-256: {hashlib.sha256(source).hexdigest()}
// Data copyright 2025 Unicode, Inc.; see licenses/Unicode-3.0.txt.

#include <cstdint>

namespace bridge::telegram::detail {{

struct EmojiScalarRange {{
  std::uint32_t first;
  std::uint32_t last;
}};

inline constexpr EmojiScalarRange emoji_scalar_ranges[] = {{
{entries}
}};

}} // namespace bridge::telegram::detail
"""
args.output.write_text(header, encoding="utf-8")
print(f"Generated {len(ranges)} ranges in {args.output}")
